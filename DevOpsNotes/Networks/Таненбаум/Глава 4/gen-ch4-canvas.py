import json
import os

NODES, EDGES = [], []
_counter = [0]


def _uid(prefix):
    _counter[0] += 1
    return f"{prefix}{_counter[0]}"


def node(x, y, w, h, text, color="1"):
    """Текстовый узел. Возвращает свой id (строкой!) — рёбра ссылаются на него."""
    nid = _uid("n")
    NODES.append({"id": nid, "type": "text", "x": x, "y": y,
                  "width": w, "height": h, "color": color, "text": text})
    return nid


def filenode(x, y, w, h, fname):
    fid = _uid("f")
    NODES.append({"id": fid, "type": "file", "file": fname,
                  "x": x, "y": y, "width": w, "height": h})
    return fid


def edge(a, b, label=None):
    e = {"id": _uid("e"), "fromNode": a, "toNode": b,
         "fromSide": "right", "toSide": "left",
         "fromEnd": "none", "toEnd": "arrow", "color": "4"}
    if label:
        e["label"] = label
    EDGES.append(e)


